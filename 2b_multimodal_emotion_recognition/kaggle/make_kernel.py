"""Build a Kaggle GPU job (script kernel) that runs this project on Kaggle.

The project code is packed into the kernel script as a base64 tarball, so the job needs no
GitHub access; the TESS dataset is attached as a Kaggle dataset source. Every number in
Results/ was produced by these jobs (logs in logs/).

    python kaggle/make_kernel.py full      --user <kaggle-username>   # everything (~5 h on a T4)
    python kaggle/make_kernel.py ablation  --user <kaggle-username>   # speech front-end ablation (~1 h)
    python kaggle/make_kernel.py analyses  --user <kaggle-username>   # layer probes + prosody baseline (~20 min)
    python kaggle/make_kernel.py capacity  --user <kaggle-username>   # pre-registered head-capacity study (~1.5 h)
    python kaggle/make_kernel.py augment   --user <kaggle-username>   # pre-registered augmentation study
    python kaggle/make_kernel.py noise     --user <kaggle-username>   # retrain + regenerate the noise study
    python kaggle/make_kernel.py backbones --user <kaggle-username>   # pre-registered encoder study (4)
    kaggle kernels push -p kaggle/build/<job>
    kaggle kernels output <kaggle-username>/mer-tess-<job> -p <dir>  # then copy runs/ and Results/ back

Requires the Kaggle API (`pip install kaggle`, token in ~/.kaggle).
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CODE = ["common", "models", "analysis", "prepare_data.py", "run_all.py", "requirements.txt",
        "Results/augmentation_lr_predictions.csv"]  # reference for check C1 of pre-registration 4

JOBS = {
    "full": [["prepare_data.py", "--speech", "--text", "--asr"], ["run_all.py", "--skip-prepare"]],
    "ablation": [["prepare_data.py", "--speech"],
                 ["run_all.py", "--skip-prepare", "--skip-train", "--skip-analyses", "--ablations"]],
    "analyses": [["prepare_data.py", "--speech", "--text"],
                 ["analysis/layer_probe.py"], ["analysis/prosody_baseline.py"]],
    # pre-registration 2 (analysis/PREREGISTRATION_si_capacity.md): B1-B4 x 2 SI directions x 10 seeds
    "capacity": [["prepare_data.py", "--speech"]] + [
        [f"models/speech_pipeline/{s}.py", "--protocol", "si", "--si_seeds", "10", *a]
        for a in ([], ["--spk_norm", "true"],
                  ["--spk_norm", "true", "--dim", "64", "--dropout", "0.5", "--weight_decay", "0.05"],
                  ["--spk_norm", "true", "--head", "attnpool"])
        for s in ("train", "test")] + [["analysis/capacity_inductive.py"]],
    # pre-registration 3, part A (analysis/PREREGISTRATION_si_augmentation.md): speed-perturbation augmentation
    "augment": [["prepare_data.py", "--speech", "--speed_perturb"]] + [
        [f"models/speech_pipeline/{s}.py", "--protocol", "si", "--si_seeds", "10", "--spk_norm", "true",
         "--augment", "speed"] for s in ("train", "test")] + [["analysis/augmentation_lr.py"]],
    # pre-registration 3, part N: retrain the six noise-study models (SD + SI) and regenerate the noise study
    "noise": [["prepare_data.py", "--speech", "--text", "--asr"]] + [
        [f"models/{pipe}/{s}.py", "--protocol", proto, *a]
        for pipe, a in (("speech_pipeline", ["--features", "wavlm"]),
                        ("speech_pipeline", ["--features", "wavlm", "--spk_norm", "true"]),
                        ("text_pipeline", ["--transcripts", "asr"]),
                        ("fusion_pipeline", ["--fusion", "gated", "--transcripts", "gt"]),
                        ("fusion_pipeline", ["--fusion", "gated", "--transcripts", "asr"]),
                        ("fusion_pipeline", ["--fusion", "gated", "--transcripts", "asr", "--spk_norm", "true"]))
        for proto in ("sd", "si") for s in ("train", "test")] + [["analysis/noise_robustness.py"]],
    # pre-registration 4 (analysis/PREREGISTRATION_si_backbones.md): frozen WavLM-Large, HuBERT-Large,
    # emotion2vec base (+ the emotion2vec+ seed leakage control). The B stores are built before funasr is installed.
    "backbones": [["prepare_data.py", "--speech", "--speed_perturb"],
                  ["-m", "pip", "install", "-q", "funasr==1.4.28"],
                  ["-c", "import torch, transformers, funasr; print(torch.__version__, transformers.__version__, funasr.__version__)"],
                  ["analysis/backbone_features.py"],
                  ["analysis/backbone_study.py", "--c_sensitivity"]],
}

TEMPLATE = '''# Multimodal emotion recognition on TESS (Assignment 2b) - Kaggle job "{job}".
# Generated by kaggle/make_kernel.py; the project code is embedded below as a base64 tarball.
import base64, glob, io, os, shutil, subprocess, sys, tarfile, time
CODE_B64 = "{b64}"
STEPS = {steps}
W = "/kaggle/working/mer"
os.makedirs(W, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(CODE_B64)), mode="r:gz").extractall(W)
env = dict(os.environ, MER_DATA_DIR="/kaggle/input", MER_CACHE_DIR="/kaggle/temp/tess_cache",
           MER_RUNS_DIR=W + "/runs", PYTHONUNBUFFERED="1", PYTHONIOENCODING="utf-8",
           TOKENIZERS_PARALLELISM="false")
subprocess.call([sys.executable, "-m", "pip", "install", "-q", "tabulate"])
import torch
print("torch", torch.__version__, "cuda", torch.cuda.is_available(),
      torch.cuda.get_device_name(0) if torch.cuda.is_available() else "", flush=True)
for step in STEPS:
    t = time.time()
    print("\\n$ python", " ".join(step), flush=True)
    rc = subprocess.call([sys.executable, *step], cwd=W, env=env)
    print("  -> exit", rc, "in", round(time.time() - t), "s", flush=True)
    if rc:
        print("STEP FAILED", flush=True)
        break
os.makedirs(W + "/cache_artifacts", exist_ok=True)
for f in glob.glob("/kaggle/temp/tess_cache/*.csv") + glob.glob("/kaggle/temp/tess_cache/*zeroshot*"):
    shutil.copy(f, W + "/cache_artifacts")
for f in glob.glob(W + "/runs/*/*/*/best.pt"):
    os.remove(f)  # checkpoints are not needed downstream and would bloat the output
print("ALL_DONE", flush=True)
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("job", choices=list(JOBS))
    ap.add_argument("--user", required=True, help="Kaggle username that will own the (private) kernel")
    args = ap.parse_args()

    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for p in CODE:
            tar.add(ROOT / p, arcname=p, filter=lambda ti: None if "__pycache__" in ti.name else ti)
    script = TEMPLATE.format(job=args.job, b64=base64.b64encode(buf.getvalue()).decode(),
                             steps=json.dumps(JOBS[args.job]))
    compile(script, "kernel", "exec")  # never push a script that does not parse

    out = ROOT / "kaggle" / "build" / args.job
    out.mkdir(parents=True, exist_ok=True)
    (out / "kernel.py").write_text(script, encoding="utf-8")
    (out / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{args.user}/mer-tess-{args.job}", "title": f"mer-tess-{args.job}", "code_file": "kernel.py",
        "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
        "enable_tpu": False, "enable_internet": True,
        "dataset_sources": ["ejlok1/toronto-emotional-speech-set-tess"],
        "competition_sources": [], "kernel_sources": [], "model_sources": []}, indent=2))
    print(f"kernel written to {out}  ->  kaggle kernels push -p {out}")


if __name__ == "__main__":
    main()
